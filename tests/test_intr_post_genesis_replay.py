"""Per-path verification sets for the InTr post-genesis kit (StegVerse-org/.github#162, Lane B).

Generated by Lane B from the 240 declared paths over 16 organizations (resident-runtime/intr_path_transfer.py declared_paths). Each
IntrPostGenesisPathTests method is one callable test set in .stegverse/test-set-spec.json (id intr-path:<S>-><D>),
so a change selects every path's check through the kit's surfaces. Offline and deterministic: the sealed records
under .stegverse/intr-post-genesis/ are re-verified from the source receipts they embed; no network, no clock, no
ledger write. Nothing here is skipped or marked bypassable.
"""
from __future__ import annotations

import copy
import hashlib
import importlib.util
import json
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
KIT = ROOT / "scripts" / "intr_post_genesis_replay.py"
KIT_DIR = ROOT / ".stegverse" / "intr-post-genesis"
INBOUND = ROOT / ".stegverse" / "intr-path-transfer" / "inbound.json"
# sealed TVC-class records from the 132-ledgered kit (main 98556a33); no live record is TVC-class after SV-011 joined
TVC_EXAMPLES = ROOT / "tests" / "fixtures" / "intr-post-genesis" / "tvc-class-records"


def _kit():
    if "intr_post_genesis_replay" in sys.modules:
        return sys.modules["intr_post_genesis_replay"]
    spec = importlib.util.spec_from_file_location("intr_post_genesis_replay", KIT)
    module = importlib.util.module_from_spec(spec)
    sys.modules["intr_post_genesis_replay"] = module
    spec.loader.exec_module(module)
    return module


kit = _kit()
MANIFEST = json.loads((KIT_DIR / "manifest.json").read_text(encoding="utf-8"))


def tvc_example(path_id: str) -> dict:
    return json.loads((TVC_EXAMPLES / (kit.slug(path_id) + ".json")).read_text(encoding="utf-8"))


NEW_ORGS = {"master-records", "formalism-tests", "Infrastructure-Continuity-Ventures"}


