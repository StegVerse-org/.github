#!/usr/bin/env python3
"""InTr destination ingress + organization ledger as one reusable component (intr-ingress-ledger/v1).

The component (components/intr-ingress-ledger/v1) packages what StegGhost/.github
installed in cffd741 (advertise and serve InTr Destination) and 03d8b94 (designate
the organization ledger ref, record diagnostic closures on it), at StegGhost
da5c947, plus the InTr protocol v1 validator. ``plan`` reports, for one
organization checkout, every file and binding the install would add, what is
already identical, and every conflict or missing prerequisite as FAIL_CLOSED with
the six fields. ``install`` applies a plan with no refusal. ``verify`` checks the
installed bytes and the destination's InTr v1 conformance. Offline and
deterministic: no clock, no network, no credential; nothing is pushed.
"""
from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
import subprocess
import sys
from pathlib import Path
from typing import Any, Mapping

ROOT = Path(__file__).resolve().parents[1]
COMPONENT = ROOT / "components" / "intr-ingress-ledger" / "v1"
RECORD = ".stegverse/components/intr-ingress-ledger-v1.json"
RECORD_SCHEMA = "stegverse.component-install-record/v1"
RESULT_SCHEMA = "stegverse.component-install-plan/v1"
GOAL = "StegVerse-org/.github#162 (task SVORG-INTR-INGRESS-LEDGER-COMPONENT-001)"
ENTRYPOINT = "resident-runtime/intr_ingress_ledger_component.py plan|install --target <organization .github checkout>"
SIX_FIELDS = ("failure_code", "failed_predicate", "required_evidence_or_repair",
              "retry_entrypoint", "owning_existing_goal", "next_attempt")
ALLOW, FAIL_CLOSED = "ALLOW", "FAIL_CLOSED"


def sha(data: bytes) -> str:
    return "sha256:" + hashlib.sha256(data).hexdigest()


def load_component(component: Path = COMPONENT) -> dict[str, Any]:
    manifest = json.loads((component / "component.json").read_text(encoding="utf-8"))
    bindings = json.loads((component / "bindings.json").read_text(encoding="utf-8"))
    return {"manifest": manifest, "bindings": bindings, "root": component}


def refusal(code: str, predicate: str, repair: str, next_attempt: str, *, classification: str = "B",
            **extra: Any) -> dict[str, Any]:
    return {"disposition": FAIL_CLOSED, "failure_code": code, "failed_predicate": predicate,
            "required_evidence_or_repair": repair, "retry_entrypoint": ENTRYPOINT, "owning_existing_goal": GOAL,
            "next_attempt": next_attempt, "classification": classification, **extra}


def _read_json(path: Path) -> Any:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (FileNotFoundError, json.JSONDecodeError):
        return None


def _slug(target: Path, organization: str) -> str | None:
    kernel = target / "org-kernel" / "kernel.py"
    if not kernel.is_file():
        return None
    spec = importlib.util.spec_from_file_location("component_target_kernel", kernel)
    module = importlib.util.module_from_spec(spec)
    try:
        spec.loader.exec_module(module)
        return module.organization_slug(organization)
    except Exception:  # noqa: BLE001 - any failure is a refusal below
        return None


def context(target: Path) -> tuple[dict[str, str] | None, list[dict[str, Any]]]:
    refusals = []
    services = _read_json(target / "org-boundary/registry/services.json")
    interlock = _read_json(target / "org-runtime/interlock-intr.json")
    organization = (services or {}).get("organization") if isinstance(services, Mapping) else None
    if not isinstance(services, Mapping) or not isinstance(services.get("services"), list) or not organization:
        refusals.append(refusal("COMPONENT_SERVICE_REGISTRY_ABSENT", "TARGET_HAS_A_SERVICE_REGISTRY",
                                "org-boundary/registry/services.json naming the organization and its services",
                                "install once the organization boundary registry exists"))
    if not isinstance(interlock, Mapping) or not isinstance(interlock.get("ingress"), Mapping) \
            or not isinstance(interlock.get("egress"), Mapping):
        refusals.append(refusal("COMPONENT_INTERLOCK_DOCUMENT_ABSENT", "TARGET_HAS_AN_INTERLOCK_INTR_DOCUMENT",
                                "org-runtime/interlock-intr.json with ingress and egress objects, generated by the "
                                "organization's own boundary generator; this component binds into it and does not "
                                "author it", "install once the interlock document exists"))
    elif organization and interlock.get("organization") != organization:
        refusals.append(refusal("COMPONENT_TARGET_IDENTITY_MISMATCH", "INTERLOCK_AND_REGISTRY_NAME_ONE_ORGANIZATION",
                                "the interlock and the service registry must name the same organization",
                                "repair the target's documents first", observed=[interlock.get("organization"),
                                                                                organization]))
    slug = _slug(target, organization) if organization else None
    if organization and not slug:
        refusals.append(refusal("COMPONENT_KERNEL_SLUG_UNAVAILABLE", "TARGET_KERNEL_DERIVES_THE_ORGANIZATION_SLUG",
                                "org-kernel/kernel.py::organization_slug", "install once the kernel derives the slug"))
    if refusals:
        return None, refusals
    return {"ORGANIZATION": organization, "REPOSITORY": organization + "/.github", "SLUG": slug}, []


def render(text: str, ctx: Mapping[str, str]) -> str:
    for key, value in ctx.items():
        text = text.replace("{{" + key + "}}", value)
    return text


def _render_obj(value: Any, ctx: Mapping[str, str]) -> Any:
    return json.loads(render(json.dumps(value), ctx))


def _dump(document: Any) -> str:
    return json.dumps(document, indent=2, ensure_ascii=False) + "\n"


def planned_files(component: Mapping[str, Any], ctx: Mapping[str, str]) -> list[tuple[str, bytes]]:
    out = []
    for row in component["manifest"]["files"]:
        data = (component["root"] / row["component_file"]).read_bytes()
        if row["kind"] == "TEMPLATE":
            data = render(data.decode("utf-8"), ctx).encode("utf-8")
        out.append((row["path"], data))
    return out


def planned_documents(component: Mapping[str, Any], target: Path, ctx: Mapping[str, str]) -> tuple[dict[str, str], list]:
    """The target's JSON documents and kernel after the bindings, or refusals."""
    b = component["bindings"]
    docs, refusals, steps = {}, [], []
    services = _read_json(target / b["services_entry"]["document"])
    entry = _render_obj(b["services_entry"]["entry"], ctx)
    rows = services[b["services_entry"]["list"]]
    same = [r for r in rows if r.get(b["services_entry"]["key"]) == entry[b["services_entry"]["key"]]]
    if same and same[0] != entry:
        refusals.append(refusal("COMPONENT_BINDING_CONFLICT", "SERVICE_ENTRY_IS_ABSENT_OR_THE_COMPONENT_ENTRY",
                                "the existing " + entry["service_id"] + " service entry differs from the component's",
                                "reconcile the entry, then re-plan", document=b["services_entry"]["document"]))
    elif not same:
        services = {**services, b["services_entry"]["list"]: rows + [entry]}
        steps.append(("BIND", b["services_entry"]["document"], "service " + entry["service_id"]))
    docs[b["services_entry"]["document"]] = _dump(services)
    interlock = _read_json(target / b["interlock_ingress"]["document"])
    for name in ("interlock_ingress", "interlock_egress"):
        spec = b[name]
        section = dict(interlock[spec["object"]])
        for key, value in _render_obj(spec["set"], ctx).items():
            if key in section and section[key] != value:
                refusals.append(refusal("COMPONENT_BINDING_CONFLICT", "INTERLOCK_BINDING_IS_ABSENT_OR_THE_COMPONENT_BINDING",
                                        spec["object"] + "." + key + " differs from the component's",
                                        "reconcile the binding, then re-plan", document=spec["document"]))
            elif key not in section:
                section[key] = value
                steps.append(("BIND", spec["document"], spec["object"] + "." + key))
        interlock = {**interlock, spec["object"]: section}
    docs[b["interlock_ingress"]["document"]] = _dump(interlock)
    k = b["kernel"]
    kernel = (target / k["document"]).read_text(encoding="utf-8")
    if k["already"] not in kernel:
        if kernel.count(k["replace"]["before"]) != 1:
            refusals.append(refusal("COMPONENT_KERNEL_HB_REFERENCE_UNSUPPORTED", "KERNEL_TAKES_A_SUPPLIED_EPOCH",
                                    "org-kernel/kernel.py hb_reference must accept a supplied epoch (" + k["requires"]
                                    + "); the component patches only the known pre-epoch form",
                                    "add the supplied-epoch form to the kernel, then re-plan", document=k["document"]))
        else:
            kernel = kernel.replace(k["replace"]["before"], k["replace"]["after"])
            steps.append(("PATCH", k["document"], "hb_reference takes a supplied epoch"))
    docs[k["document"]] = kernel
    return {"documents": docs, "steps": steps}, refusals


def plan(target: Path | str, component: Mapping[str, Any] | None = None) -> dict[str, Any]:
    target = Path(target)
    component = component or load_component()
    ctx, refusals = context(target)
    if ctx is None:
        return {"schema": RESULT_SCHEMA, "target": str(target), **refusals[0], "refusals": refusals}
    steps, writes = [], {}
    for path, data in planned_files(component, ctx):
        existing = target / path
        if existing.is_file() and existing.read_bytes() == data:
            steps.append(("IDENTICAL", path, sha(data)))
        elif existing.exists():
            refusals.append(refusal("COMPONENT_FILE_CONFLICT", "COMPONENT_FILE_IS_ABSENT_OR_IDENTICAL",
                                    path + " exists with other bytes; the component does not overwrite",
                                    "reconcile the file with the component (or adopt its bytes), then re-plan",
                                    path=path, observed_sha256=sha(existing.read_bytes()) if existing.is_file() else None,
                                    expected_sha256=sha(data)))
        else:
            steps.append(("ADD", path, sha(data)))
            writes[path] = data
    docs, doc_refusals = planned_documents(component, target, ctx)
    refusals += doc_refusals
    record = {"schema": RECORD_SCHEMA, "component": "intr-ingress-ledger/v1", "organization": ctx["ORGANIZATION"],
              "address": ctx["SLUG"] + ".intr-destination", "owning_existing_goal": GOAL,
              "authentic_receipt": False,
              "files": [{"path": p, "sha256": sha(d)} for p, d in planned_files(component, ctx)]}
    base = {"schema": RESULT_SCHEMA, "target": str(target), "context": ctx,
            "steps": [list(s) for s in steps + docs["steps"]], "record": record}
    if refusals:
        return {**base, **refusals[0], "refusals": refusals}
    return {**base, "disposition": ALLOW, "_writes": writes, "_documents": docs["documents"]}


def install(target: Path | str, component: Mapping[str, Any] | None = None) -> dict[str, Any]:
    result = plan(target, component)
    if result["disposition"] != ALLOW:
        return result
    target = Path(target)
    for path, data in result.pop("_writes").items():
        (target / path).parent.mkdir(parents=True, exist_ok=True)
        (target / path).write_bytes(data)
    for path, text in result.pop("_documents").items():
        if (target / path).read_text(encoding="utf-8") != text:
            (target / path).write_text(text, encoding="utf-8")
    (target / RECORD).parent.mkdir(parents=True, exist_ok=True)
    (target / RECORD).write_text(_dump(result["record"]), encoding="utf-8")
    return {**result, "installed": True}


def verify(target: Path | str) -> dict[str, Any]:
    target = Path(target)
    record = _read_json(target / RECORD)
    if not isinstance(record, Mapping):
        return refusal("COMPONENT_NOT_INSTALLED", "TARGET_RECORDS_THE_COMPONENT_INSTALL", RECORD,
                       "run install, then verify")
    for row in record["files"]:
        f = target / row["path"]
        if not f.is_file() or sha(f.read_bytes()) != row["sha256"]:
            return refusal("COMPONENT_FILE_DRIFT", "INSTALLED_FILE_IS_THE_COMPONENT_BYTES", row["path"],
                           "re-install or reconcile", path=row["path"])
    run = subprocess.run([sys.executable, "org-runtime/intr_protocol.py", "conform", "--org", record["organization"]],
                         cwd=target, capture_output=True, text=True)
    try:
        conform = json.loads(run.stdout)
    except json.JSONDecodeError:
        conform = {"disposition": FAIL_CLOSED, "detail": run.stderr[-2000:]}
    if conform.get("disposition") != ALLOW:
        return {**refusal("COMPONENT_DESTINATION_NONCONFORMANT", "INSTALLED_DESTINATION_CONFORMS_TO_INTR_V1",
                          "the installed destination must be ALLOW under org-runtime/intr_protocol.py conform",
                          "repair the failing predicate, then re-verify"), "conformance": conform}
    return {"disposition": ALLOW, "organization": record["organization"], "address": record["address"],
            "files": len(record["files"]), "conformance": conform["disposition"]}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("command", choices=("plan", "install", "verify"))
    parser.add_argument("--target", required=True)
    args = parser.parse_args(argv)
    result = {"plan": plan, "install": install, "verify": verify}[args.command](args.target)
    result = {k: v for k, v in result.items() if not k.startswith("_")}
    print(json.dumps(result, indent=2, sort_keys=True))
    return 0 if result["disposition"] == ALLOW else 1


if __name__ == "__main__":
    raise SystemExit(main())
